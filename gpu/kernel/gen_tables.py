"""Generate lobe_tables.h from MoonRay's albedo tables (Apache-2.0, DreamWorks Animation LLC).
Values are copied as text, so nothing is rounded. Source files are only read."""
import re, sys, pathlib
SRC = pathlib.Path(sys.argv[1])  # .../shading/bsdf/cook_torrance/energy_compensation
OUT = pathlib.Path(sys.argv[2])
def arrays(path, cls):
    t = path.read_text()
    r = {}
    for m in re.finditer(cls + r'::(m\w+)\s*\[[^\]]*\]\s*=\s*\{(.*?)\}', t, re.S):
        r[m.group(1)] = re.findall(r'[-+]?\d+\.\d*(?:[eE][-+]?\d+)?f?', m.group(2))
    return r
refl = arrays(SRC / 'ReflectionAlbedo.h', 'ReflectionAlbedo')
tran = arrays(SRC / 'TransmissionAlbedo.h', 'TransmissionAlbedo')
want = [('nk_tbl_beckmann_e', refl['mBeckmannE'], 33**2), ('nk_tbl_ggx_e', refl['mGGXE'], 33**2),
        ('nk_tbl_beckmann_one_minus_eavg', refl['mBeckmannOneMinusEavg'], 33),
        ('nk_tbl_ggx_one_minus_eavg', refl['mGGXOneMinusEavg'], 33),
        ('nk_tbl_trans_e', tran['mE'], 33**3), ('nk_tbl_trans_e_exit', tran['mEExit'], 33**3),
        ('nk_tbl_trans_one_minus_eavg', tran['mOneMinusEavg'], 33**2),
        ('nk_tbl_trans_one_minus_eavg_exit', tran['mOneMinusEavgExit'], 33**2)]
def ispc_array(path, name):
    m = re.search(name + r'\s*\[[^\]]*\]\s*=\s*\{(.*?)\}', path.read_text(), re.S)
    return re.findall(r'[-+]?\d+\.\d*(?:[eE][-+]?\d+)?f?', m.group(1))
FAB = SRC.parents[2] / 'ispc' / 'bsdf' / 'fabric'
want += [('nk_tbl_velvet_norm', ispc_array(FAB / 'BsdfFabricVelvet.ispc', 'BsdfFabricVelvet_precomputedNormalizationTable'), 20),
         ('nk_tbl_velvet_albedo', ispc_array(FAB / 'VelvetAlbedoTable.isph', 'VelvetAlbedo_albedoTable'), 2000)]
o = ['// Copyright 2023-2024 DreamWorks Animation LLC', '// SPDX-License-Identifier: Apache-2.0', '//',
     '// GENERATED by gen_tables.py. Do not edit.',
     '// Origin: moonray/lib/rendering/shading/bsdf/cook_torrance/energy_compensation/',
     '//         ReflectionAlbedo.h, TransmissionAlbedo.h. Values unchanged, only reformatted.',
     '//         And shading/ispc/bsdf/fabric/BsdfFabricVelvet.ispc, VelvetAlbedoTable.isph.',
     '// Host-side data. Upload these to the GPU and hand lobes.h a LobeTables of pointers.',
     '#pragma once', '']
for name, vals, n in want:
    if len(vals) != n: sys.exit(f'{name}: {len(vals)} values, expected {n}')
    o.append(f'static const float {name}[{n}] = {{')
    o += [','.join(vals[i:i+33]) + ',' for i in range(0, n, 33)]
    o.append('};\n')
OUT.write_text('\n'.join(o), newline='\n')
print('wrote', OUT, OUT.stat().st_size)
