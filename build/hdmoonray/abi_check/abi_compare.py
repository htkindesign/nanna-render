"""Compare the sizes recorded by abi_sizes.cc under oneTBB and TBB 2020, and write the static_assert header.

abi_asserts.h asserts each class's size under TBB 2020 against the oneTBB size usd_ms.dll was built with. Only classes
with equal sizes get an active assert, so it can guard the build. A class that differs is printed, and is listed in the
header as a comment: hdMoonray must only ever hold that class by pointer or reference and reach it through exported functions.

Usage: python -I abi_compare.py <onetbb.obj> <tbb2020.obj> <abi_asserts.h>     exit 0 when all sizes match, 1 otherwise
"""
import struct
import sys


def records(path):
    data = open(path, "rb").read()
    found, at = {}, data.find(b"ABIREC__")
    while at >= 0:
        name = data[at + 8:at + 64].split(b"\0")[0].decode("ascii")
        found[name] = struct.unpack_from("<Q", data, at + 64)[0]
        at = data.find(b"ABIREC__", at + 72)
    return found


def main():
    onetbb, tbb2020 = records(sys.argv[1]), records(sys.argv[2])
    if not onetbb or set(onetbb) != set(tbb2020):
        raise SystemExit(f"record lists differ or are empty: {sorted(set(onetbb) ^ set(tbb2020))}")
    lines = ["// Generated by abi_compare.py. Include after the USD headers named in abi_sizes.cc, compiled with TBB 2020.", ""]
    differ = 0
    for name in sorted(onetbb):
        a, b = onetbb[name], tbb2020[name]
        print(f"{'same' if a == b else 'DIFFERENT'} {name}: oneTBB {a}, TBB 2020 {b}")
        if a == b:
            lines.append(f"static_assert(sizeof(PXR_NS::{name}) == {a}, \"{name} changed size against usd_ms.dll\");")
        else:
            differ += 1
            lines.append(f"// DIFFERENT {name}: oneTBB {a}, TBB 2020 {b}. Pointer or reference only.")
    with open(sys.argv[3], "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{differ} of {len(onetbb)} differ")
    return 1 if differ else 0


if __name__ == "__main__":
    sys.exit(main())
